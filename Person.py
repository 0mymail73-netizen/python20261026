"""간단한 Person 클래스와 인스턴스별 속성 사용 예제를 제공한다.

파일을 직접 실행하면 두 객체를 생성하고, 첫 번째 객체의 이름만 변경한 뒤
각 객체의 이름을 출력한다. 이를 통해 인스턴스 속성이 객체마다 독립적으로
유지되는 동작을 확인할 수 있다.
"""


class Person:
    def __init__(self):
        """새 Person 객체를 만들고 기본 이름을 인스턴스 속성으로 설정한다.

        ``name``은 클래스 전체가 공유하는 클래스 속성이 아니라 각 객체에
        저장되는 인스턴스 속성이다. 따라서 한 객체의 ``name``을 변경해도
        다른 Person 객체의 이름에는 영향을 주지 않는다.
        """
        self.name = "default name"

    def print(self):
        """이 객체의 이름을 표준 출력에 한 줄로 표시한다.

        이름은 호출 시점에 ``self.name``에서 읽으므로, 호출 전에 이름을
        변경하면 변경된 값이 출력된다. 이 메서드는 출력만 수행하며
        명시적인 반환값은 없다.
        """
        print("My name is {0}".format(self.name))


# 서로 독립된 두 인스턴스를 만들고, p1의 이름만 변경한다.
p1 = Person()
p2 = Person()
p1.name = "전우치"

# p1은 변경된 이름을, p2는 생성 시 설정된 기본 이름을 출력한다.
p1.print()
p2.print()
